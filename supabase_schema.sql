-- Sermon Tracking and Bible Verse Management System
-- Supabase PostgreSQL Schema & Initial Setup
-- ==============================================================================

-- 1. Users Table
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    full_name TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('ADMIN', 'VIEWER')),
    pw_hash TEXT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Case-insensitive lookup index on username
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username_lower ON public.users (LOWER(username));

-- 2. Sessions Table
CREATE TABLE IF NOT EXISTS public.sessions (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_sessions_user ON public.sessions (user_id);
CREATE INDEX IF NOT EXISTS idx_sessions_expires ON public.sessions (expires_at);

-- 3. Sermons Table
CREATE TABLE IF NOT EXISTS public.sermons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    pastor TEXT NOT NULL,
    sermon_date DATE NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_sermons_date ON public.sermons (sermon_date DESC, id DESC);

-- 4. Verses Table (linked to sermons)
CREATE TABLE IF NOT EXISTS public.verses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sermon_id BIGINT NOT NULL REFERENCES public.sermons(id) ON DELETE CASCADE,
    book TEXT NOT NULL,
    chapter INTEGER NOT NULL,
    verse_start INTEGER,
    verse_end INTEGER,
    verse_list TEXT NOT NULL DEFAULT '',
    translation TEXT NOT NULL DEFAULT 'KJV',
    verse_text TEXT NOT NULL DEFAULT '',
    highlights JSONB NOT NULL DEFAULT '[]'::jsonb,
    note TEXT NOT NULL DEFAULT '',
    position INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_verses_sermon_pos ON public.verses (sermon_id, position ASC);

-- 5. Auto-update timestamp trigger for sermons
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS set_sermons_updated_at ON public.sermons;
CREATE TRIGGER set_sermons_updated_at
    BEFORE UPDATE ON public.sermons
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_updated_at();

-- 6. Enable Row Level Security (RLS)
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sermons ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.verses ENABLE ROW LEVEL SECURITY;

-- Public read policies for Sermons & Verses (Viewer Panel)
CREATE POLICY "Allow public read access to sermons" ON public.sermons
    FOR SELECT USING (true);

CREATE POLICY "Allow public read access to verses" ON public.verses
    FOR SELECT USING (true);

-- Full access for service role or application backend
CREATE POLICY "Allow service role full access to users" ON public.users
    FOR ALL USING (true) WITH CHECK (true);

CREATE POLICY "Allow service role full access to sessions" ON public.sessions
    FOR ALL USING (true) WITH CHECK (true);

CREATE POLICY "Allow service role full access to sermons" ON public.sermons
    FOR ALL USING (true) WITH CHECK (true);

CREATE POLICY "Allow service role full access to verses" ON public.verses
    FOR ALL USING (true) WITH CHECK (true);
