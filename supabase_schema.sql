-- Supabase is the source of truth. No passwords or application sessions in public.
CREATE TABLE IF NOT EXISTS public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  username text UNIQUE, full_name text NOT NULL DEFAULT '',
  role text NOT NULL DEFAULT 'VIEWER' CHECK (role IN ('ADMIN','VIEWER')),
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.sermons (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL CHECK (length(trim(title)) BETWEEN 1 AND 200),
  pastor text NOT NULL CHECK (length(trim(pastor)) BETWEEN 1 AND 120),
  sermon_date date NOT NULL, description text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.verses (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sermon_id bigint NOT NULL REFERENCES public.sermons(id) ON DELETE CASCADE,
  book text NOT NULL, chapter integer NOT NULL CHECK (chapter BETWEEN 1 AND 150),
  verse_start integer, verse_end integer, verse_list text NOT NULL DEFAULT '',
  translation text NOT NULL DEFAULT 'KJV', verse_text text NOT NULL DEFAULT '',
  highlights jsonb NOT NULL DEFAULT '[]', note text NOT NULL DEFAULT '',
  position integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_sermons_date ON public.sermons(sermon_date DESC,id DESC);
CREATE INDEX IF NOT EXISTS idx_verses_sermon_pos ON public.verses(sermon_id,position,id);

CREATE OR REPLACE FUNCTION public.handle_updated_at() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN NEW.updated_at = now(); RETURN NEW; END $$;
DROP TRIGGER IF EXISTS set_sermons_updated_at ON public.sermons;
CREATE TRIGGER set_sermons_updated_at BEFORE UPDATE ON public.sermons
FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();
DROP TRIGGER IF EXISTS set_profiles_updated_at ON public.profiles;
CREATE TRIGGER set_profiles_updated_at BEFORE UPDATE ON public.profiles
FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

-- Trigger-only privilege: role comes exclusively from server-managed app metadata.
-- Public signup never grants admin, including the first signup.
CREATE OR REPLACE FUNCTION public.handle_new_user() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  INSERT INTO public.profiles(id,username,full_name,role,active)
  VALUES (NEW.id, NEW.id::text,
    coalesce(NEW.raw_user_meta_data->>'full_name',split_part(NEW.email,'@',1)),
    CASE WHEN NEW.raw_app_meta_data->>'role' = 'ADMIN' THEN 'ADMIN' ELSE 'VIEWER' END,
    true);
  RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION public.handle_new_user() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

