GRANT SELECT ON public.profiles TO authenticated;
CREATE POLICY own_profile ON public.profiles FOR SELECT TO authenticated
USING (id=(SELECT auth.uid()));

-- Invoker rights: profiles has a simple own-row policy, so no recursive policy or definer bypass.
CREATE OR REPLACE FUNCTION public.is_admin() RETURNS boolean
LANGUAGE sql STABLE SECURITY INVOKER SET search_path = '' AS $$
 SELECT EXISTS(SELECT 1 FROM public.profiles
 WHERE id=(SELECT auth.uid()) AND role='ADMIN' AND active=true)
$$;
REVOKE ALL ON FUNCTION public.is_admin() FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.is_admin() TO authenticated;
GRANT USAGE ON SCHEMA public TO anon,authenticated;
GRANT SELECT ON public.sermons,public.verses TO anon,authenticated;
GRANT INSERT,UPDATE,DELETE ON public.sermons,public.verses TO authenticated;
REVOKE INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER ON public.sermons,public.verses FROM anon;
GRANT USAGE,SELECT ON SEQUENCE public.sermons_id_seq,public.verses_id_seq TO authenticated;
CREATE POLICY public_sermons ON public.sermons FOR SELECT TO anon,authenticated USING (true);
CREATE POLICY public_verses ON public.verses FOR SELECT TO anon,authenticated USING (true);
CREATE POLICY admin_sermons_insert ON public.sermons FOR INSERT TO authenticated WITH CHECK ((SELECT public.is_admin()));
CREATE POLICY admin_sermons_update ON public.sermons FOR UPDATE TO authenticated USING ((SELECT public.is_admin())) WITH CHECK ((SELECT public.is_admin()));
CREATE POLICY admin_sermons_delete ON public.sermons FOR DELETE TO authenticated USING ((SELECT public.is_admin()));
CREATE POLICY admin_verses_insert ON public.verses FOR INSERT TO authenticated WITH CHECK ((SELECT public.is_admin()));
CREATE POLICY admin_verses_update ON public.verses FOR UPDATE TO authenticated USING ((SELECT public.is_admin())) WITH CHECK ((SELECT public.is_admin()));
CREATE POLICY admin_verses_delete ON public.verses FOR DELETE TO authenticated USING ((SELECT public.is_admin()));

-- Atomic creation: a failed passage insert rolls back the sermon too.
CREATE OR REPLACE FUNCTION public.create_sermon_record(p_sermon jsonb,p_verses jsonb DEFAULT '[]')
RETURNS bigint LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE sid bigint;
BEGIN
 IF NOT public.is_admin() THEN RAISE EXCEPTION 'Administrator access required' USING ERRCODE='42501'; END IF;
 INSERT INTO public.sermons(title,pastor,sermon_date,description)
 VALUES(p_sermon->>'title',p_sermon->>'pastor',(p_sermon->>'sermon_date')::date,coalesce(p_sermon->>'description',''))
 RETURNING id INTO sid;
 INSERT INTO public.verses(sermon_id,book,chapter,verse_start,verse_end,verse_list,translation,verse_text,highlights,note,position)
 SELECT sid,v->>'book',(v->>'chapter')::integer,(v->>'verse_start')::integer,(v->>'verse_end')::integer,
 coalesce(v->>'verse_list',''),coalesce(v->>'translation','KJV'),coalesce(v->>'verse_text',''),
 coalesce(v->'highlights','[]'::jsonb),coalesce(v->>'note',''),(ord-1)::integer
 FROM jsonb_array_elements(p_verses) WITH ORDINALITY AS a(v,ord);
 RETURN sid;
END $$;
CREATE OR REPLACE FUNCTION public.reorder_sermon_verses(p_sermon_id bigint,p_order bigint[])
RETURNS void LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE actual bigint[];
BEGIN
 IF NOT public.is_admin() THEN RAISE EXCEPTION 'Administrator access required' USING ERRCODE='42501'; END IF;
 PERFORM 1 FROM public.sermons WHERE id=p_sermon_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Sermon not found'; END IF;
 SELECT coalesce(array_agg(id ORDER BY id),'{}'::bigint[]) INTO actual FROM public.verses WHERE sermon_id=p_sermon_id;
 IF p_order IS NULL OR actual IS DISTINCT FROM ARRAY(SELECT x FROM unnest(p_order) x ORDER BY x)
 THEN RAISE EXCEPTION 'Order must include every passage exactly once'; END IF;
 UPDATE public.verses v SET position=o.ord-1
 FROM unnest(p_order) WITH ORDINALITY AS o(id,ord)
 WHERE v.id=o.id AND v.sermon_id=p_sermon_id;
END $$;
REVOKE ALL ON FUNCTION public.create_sermon_record(jsonb,jsonb),public.reorder_sermon_verses(bigint,bigint[]) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.create_sermon_record(jsonb,jsonb),public.reorder_sermon_verses(bigint,bigint[]) TO authenticated;
